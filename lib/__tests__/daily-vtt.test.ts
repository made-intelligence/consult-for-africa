import { describe, expect, it } from "vitest";
import { roomNameFor, vttToText } from "@/lib/daily";

describe("vttToText", () => {
  it("reads voice tags and joins one speaker's consecutive cues", () => {
    const vtt = `WEBVTT

1
00:00:01.000 --> 00:00:03.000
<v Debo Odulana>I'll send the tariff sheet</v>

2
00:00:03.000 --> 00:00:05.000
<v Debo Odulana>by Friday.</v>

3
00:00:05.000 --> 00:00:07.000
<v Dr Ade>Thank you.</v>
`;
    expect(vttToText(vtt)).toBe("Debo Odulana: I'll send the tariff sheet by Friday.\nDr Ade: Thank you.");
  });

  it("reads a leading name and colon", () => {
    const vtt = "WEBVTT\n\n00:00:01.000 --> 00:00:02.000\nEzinne: Noted.\n";
    expect(vttToText(vtt)).toBe("Ezinne: Noted.");
  });

  it("keeps the words when there is no speaker", () => {
    const vtt = "WEBVTT\r\n\r\n00:00:01.000 --> 00:00:02.000\r\nwe will revert next week\r\n\r\n00:00:02.000 --> 00:00:03.000\r\non the staffing\r\n";
    expect(vttToText(vtt)).toBe("we will revert next week on the staffing");
  });

  it("ignores the header and notes", () => {
    expect(vttToText("WEBVTT\n\nNOTE generated by Daily\n")).toBe("");
  });
});

describe("roomNameFor", () => {
  it("keeps C4A rooms apart from Mezo's", () => {
    expect(roomNameFor("cmh1AbC_9")).toBe("cfa-cmh1abc-9");
  });
});
